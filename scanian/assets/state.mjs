export const DATA_PATH = 'scanian/data/scanian.json';
export const clone = value => structuredClone(value);
const stable = value => JSON.stringify(value, (_, v) => v && !Array.isArray(v) && typeof v === 'object' ? Object.fromEntries(Object.keys(v).sort().map(k => [k, v[k]])) : v);
export const equal = (a, b) => stable(a) === stable(b);
const meaningValue = m => m && {id:m.id, desc:m.desc};
export const sameContent = (a,b) => equal(a.meanings.map(meaningValue), b.meanings.map(meaningValue)) && equal(a.questions,b.questions) && equal(a.notebook.items,b.notebook.items);

// Old backups and browser drafts use numeric note IDs. Map them consistently
// so they still merge with the UUIDs generated by Pages CMS.
export function noteId(id) {
  if(!Number.isSafeInteger(id) || id<0)return id;
  const hex=id.toString(16).padStart(15,'0');
  return `00000000-0000-4000-8${hex.slice(0,3)}-${hex.slice(3)}`;
}
const validNoteId=id=>typeof id==='string' && /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(id);
const compareIds=(a,b)=>typeof a.id==='number'&&typeof b.id==='number'?a.id-b.id:String(a.id).localeCompare(String(b.id));

export function validate(state, records) {
  state=clone(state);
  // Pages CMS omits empty strings and empty lists when it saves JSON.
  if(state && typeof state==='object'){
    if(state.questions===undefined)state.questions=[];
    if(state.notebook===undefined)state.notebook={items:[]};
    if(state.notebook && typeof state.notebook==='object' && state.notebook.items===undefined)state.notebook.items=[];
  }
  if (!state || state.version !== 1 || !Array.isArray(state.meanings) || !Array.isArray(state.questions) || !Array.isArray(state.notebook?.items)) throw new Error('This backup has an unknown format.');
  const recordMap = new Map(records.map(r=>[r.id,r]));
  const ids = new Set(recordMap.keys());
  const seen = new Set();
  if(state.meanings.length !== records.length) throw new Error('The number of auctions does not match.');
  for(const m of state.meanings) {
    if(!m || typeof m!=='object')throw new Error('An auction is invalid.');
    if(m.desc===undefined)m.desc='';
    if(!ids.has(m.id) || seen.has(m.id) || typeof m.desc !== 'string' || m.desc.length > 50000) throw new Error('An auction is missing or invalid.');
    seen.add(m.id);
    if(Object.keys(m).some(k=>!['id','desc','meaningUpdatedAt','auction'].includes(k))) throw new Error('The backup has unknown meaning fields.');
    m.auction=recordMap.get(m.id).pathPretty;
  }
  for(const [items,type] of [[state.questions,'question'],[state.notebook.items,'rule']]) {
    const unique = new Set();
    for(const item of items) {
      if(!item || typeof item!=='object')throw new Error(`A ${type} is invalid.`);
      item.id=noteId(item.id);
      if(type==='question'){
        if(item.answer===undefined)item.answer='';
        if(item.note===undefined)item.note='';
      }
      if(!validNoteId(item.id) || unique.has(item.id)) throw new Error(`A ${type} ID is invalid.`);
      unique.add(item.id);
      if(type==='question' && (!ids.has(item.recordId) || typeof item.question!=='string' || typeof item.answer!=='string' || !['open','answered'].includes(item.status))) throw new Error('A question is invalid.');
      if(type==='rule' && typeof item.text!=='string') throw new Error('A rule is invalid.');
    }
  }
  return clone(state);
}

export function mergeStates(base, local, remote) {
  const conflicts=[];
  function mergeList(name,b,l,r,compare=equal) {
    const maps=[b,l,r].map(items=>new Map(items.map(x=>[x.id,x])));
    const ids=new Set([...r,...l,...b].map(x=>x.id));
    const result=[];
    for(const id of ids) {
      const [old,mine,theirs]=maps.map(m=>m.get(id));
      let value;
      if(compare(mine,old)) value=theirs;
      else if(compare(theirs,old) || compare(mine,theirs)) value=mine;
      else {conflicts.push({collection:name,id,base:old,local:mine,remote:theirs});value=mine;}
      if(value!==undefined) result.push(clone(value));
    }
    return result.sort(compareIds);
  }
  const result={version:1,updatedAt:new Date().toISOString(),
    meanings:mergeList('meanings',base.meanings,local.meanings,remote.meanings,(a,b)=>equal(meaningValue(a),meaningValue(b))),
    questions:mergeList('questions',base.questions,local.questions,remote.questions),
    notebook:{updatedAt:new Date().toISOString(),items:mergeList('rules',base.notebook.items,local.notebook.items,remote.notebook.items)}};
  return {result,conflicts};
}

export function resolveConflicts(merged, choices) {
  const result=clone(merged.result);
  for(const conflict of merged.conflicts) {
    const list=conflict.collection==='rules'?result.notebook.items:result[conflict.collection];
    const value=choices.get(`${conflict.collection}:${conflict.id}`)==='remote'?conflict.remote:conflict.local;
    const index=list.findIndex(x=>x.id===conflict.id);
    if(index>=0)list.splice(index,1);
    if(value!==undefined)list.push(clone(value));
    list.sort(compareIds);
  }
  return result;
}

export function encode(text) {
  const bytes=new TextEncoder().encode(text);
  let binary='';
  for(let i=0;i<bytes.length;i+=8192)binary+=String.fromCharCode(...bytes.subarray(i,i+8192));
  return btoa(binary);
}
export function decode(text) {return new TextDecoder().decode(Uint8Array.from(atob(text.replace(/\s/g,'')),c=>c.charCodeAt(0)));}

export async function readRemote(request,records) {
  const file=await request(`${API}/contents/${DATA_PATH}?ref=main`);
  if(!file.sha || file.encoding!=='base64' || !file.content) throw new Error('GitHub did not return the data file.');
  return {state:validate(JSON.parse(decode(file.content)),records),sha:file.sha};
}

export async function saveRemote(request,records,base,local) {
  for(let attempt=0;attempt<3;attempt++) {
    const remote=await readRemote(request,records);
    const merged=mergeStates(base,local,remote.state);
    if(merged.conflicts.length) return {conflict:merged,remote:remote.state};
    const state=validate(merged.result,records);
    if(sameContent(state,remote.state))return {state:remote.state};
    try {
      const result=await request(`${API}/contents/${DATA_PATH}`,{method:'PUT',body:JSON.stringify({message:'Update Scanian meanings and partnership notes',branch:'main',sha:remote.sha,content:encode(JSON.stringify(state)+'\n')})});
      if(!result.commit?.sha)throw new Error('GitHub did not confirm the save.');
      return {state,commit:result.commit.sha};
    } catch(error) {if(error.status!==409 || attempt===2)throw error;}
  }
}
